"""Bake the DNPA camping polygons into small Connect IQ JSON resources.
Coordinates are integers in 1e-5 degrees relative to (LON0, LAT0). One resource per polygon part,
plus an index of bounding boxes so the watch only loads polygons near you."""
import json, sys, os
from shapely.geometry import shape
src, out = sys.argv[1], sys.argv[2]
LON0, LAT0, Q = -4.2, 50.35, 1e5
TOL = 0.0001  # ~7-11 m
parts = []
for f in json.load(open(src))['features']:
    g = shape(f['geometry'])
    for p in ([g] if g.geom_type == 'Polygon' else g.geoms):
        p = p.simplify(TOL, preserve_topology=True)
        rings = []
        for r in [p.exterior, *p.interiors]:
            cs = list(r.coords)[:-1]
            flat = []
            for x, y in cs:
                flat += [round((x - LON0) * Q), round((y - LAT0) * Q)]
            if len(flat) >= 6: rings.append(flat)
        b = [round((v - o) * Q) for v, o in zip(p.bounds, (LON0, LAT0, LON0, LAT0))]
        parts.append((b, rings))
os.makedirs(out + '/camp', exist_ok=True)
xml = ['<resources>']
for i, (b, rings) in enumerate(parts):
    json.dump(rings, open(f'{out}/camp/p{i}.json', 'w'), separators=(',', ':'))
    xml.append(f'  <jsonData id="camp{i}" filename="camp/p{i}.json"/>')
json.dump([b for b, _ in parts], open(f'{out}/camp/index.json', 'w'), separators=(',', ':'))
xml.append('  <jsonData id="campIndex" filename="camp/index.json"/>')
xml.append('</resources>')
open(f'{out}/camp.xml', 'w').write('\n'.join(xml) + '\n')
mc = ['// Generated by tools/bake_camp.py: do not edit.', 'import Toybox.Lang;', 'import Toybox.WatchUi;', '',
      'module CampData {', f'    const LON0 = {LON0}d;', f'    const LAT0 = {LAT0}d;', f'    const Q = {Q:.1f}d;', '    function ids() as Array {', '        return [']
mc += [f'            Rez.JsonData.camp{i},' for i in range(len(parts))]
mc += ['        ];', '    }', '}']
open(sys.argv[3], 'w').write('\n'.join(mc) + '\n')
n = [sum(len(r) // 2 for r in rr) for _, rr in parts]
print(len(parts), 'parts', sum(n), 'vertices, max', max(n), 'bytes', sum(os.path.getsize(f'{out}/camp/p{i}.json') for i in range(len(parts))))
